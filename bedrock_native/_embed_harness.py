"""Bedrock standalone embedding harness (Phase B).

Generates ``main.c`` that embeds CPython, imports the transpiled ``obf``
extension sitting next to the executable, and calls ``obf.main()`` —
producing a standalone ``app.exe`` shipped with ``python311.dll``, the
``.pyd``, and a stdlib subset, so no host Python install is required.

The leak-resilience story (Phase 1): the obfuscated logic is native machine
code in ``obf.cp311-win_amd64.pyd``; there is no marshal blob and no
cleartext key. Phase 2 wraps it in a self-contained exe so the end user needs
nothing else. The reverser CAN still attach to the CPython runtime that ships
in the package, but the *protected logic* is native and carries no key — the
generic deobfuscator built from the leaked source is still useless.

Pipeline::

    obf.cp311-win_amd64.pyd  (built by _transpile_pipeline)
      + main.c (auto-generated here)
      + python311.lib  (CPython import library)
      -> cl /MD main.c /Fe:app.exe /link python311.lib
      + ship python311.dll + python3.dll + vcruntime140.dll + Lib/ stdlib
      + write python311._pth (embeddable-path config: "Lib\\n.")
      -> out_dir/app.exe + out_dir/obf.*.pyd + out_dir/python311.dll + ...

The ``python311._pth`` file (Microsoft's embeddable-distribution convention)
tells CPython to look in ``Lib/`` (stdlib) and ``.`` (the .pyd) and disables
PYTHONPATH / registry lookups, so the package is self-contained.
"""
import glob
import os
import shutil
import subprocess
import sys
import sysconfig
import tempfile

_HERE = os.path.dirname(os.path.abspath(__file__))
if _HERE not in sys.path:
    sys.path.insert(0, _HERE)
from _build_system import detect_build_capability  # noqa: E402


# ---------------------------------------------------------------------------
# main.c template
# ---------------------------------------------------------------------------
_MAIN_C_TEMPLATE = r'''/* Bedrock standalone embedding harness (auto-generated by _embed_harness.py).
 * Initializes CPython, inserts the executable's directory at the front of
 * sys.path so the bundled 'obf' extension imports, and calls obf.main().
 * The package ships python311.dll + Lib/ stdlib + python311._pth, so no
 * host Python install is required.
 */
#define PY_SSIZE_T_CLEAN
#include <Python.h>
#include <stdio.h>
#include <stdlib.h>
#ifdef _WIN32
#  include <windows.h>
#endif

/* Prepend the executable's own directory to sys.path so the bundled
 * 'obf.cp311-win_amd64.pyd' (shipped alongside app.exe) is importable.
 * The python311._pth file already lists "." as a path, but we prepend
 * explicitly to guarantee ordering regardless of _pth contents. */
static void _br_prepend_exe_dir(void) {
    wchar_t buf[4096];
#ifdef _WIN32
    DWORD n = GetModuleFileNameW(NULL, buf, 4096);
    if (n == 0 || n >= 4096) return;
#else
    ssize_t n = readlink("/proc/self/exe", (char*)buf, sizeof(buf));
    if (n <= 0) return;
    buf[n] = L'\0';
#endif
    /* Trim to directory. */
    wchar_t *slash = wcsrchr(buf, L'/');
    wchar_t *bslash = wcsrchr(buf, L'\\');
    wchar_t *sep = (bslash > slash) ? bslash : slash;
    if (sep) *sep = L'\0';
    PyObject *path = PySys_GetObject("path");
    if (path) {
        PyObject *wdir = PyUnicode_FromWideChar(buf, -1);
        if (wdir) {
            if (PyList_Insert(path, 0, wdir) < 0) PyErr_Clear();
            Py_DECREF(wdir);
        }
    }
}

int main(int argc, char **argv) {
    /* Decode argv to wide chars so we can pass it to Python (sys.argv). */
    wchar_t **wargv = PyMem_Calloc((size_t)argc, sizeof(wchar_t*));
    if (!wargv) return 1;
    for (int i = 0; i < argc; i++) {
        wargv[i] = Py_DecodeLocale(argv[i], NULL);
        if (!wargv[i]) wargv[i] = L"";
    }

    Py_Initialize();
    /* Populate sys.argv before any import that might read it. PySys_SetArgvEx
     * is deprecated and returns void in 3.11, so we cannot check its result. */
    PySys_SetArgvEx(argc, wargv, 0);

    _br_prepend_exe_dir();

    int rc = 0;
    PyObject *mod = PyImport_ImportModule("obf");
    if (!mod) {
        PyErr_Print();
        fprintf(stderr, "fatal: module load failed\n");
        rc = 1;
    } else {
        PyObject *main_fn = PyObject_GetAttrString(mod, "main");
        if (!main_fn) {
            PyErr_Print();
            fprintf(stderr, "fatal: entry point missing\n");
            rc = 1;
        } else if (!PyCallable_Check(main_fn)) {
            fprintf(stderr, "fatal: entry point not callable\n");
            rc = 1;
        } else {
            PyObject *result = PyObject_CallObject(main_fn, NULL);
            Py_DECREF(main_fn);
            if (!result) {
                PyErr_Print();
                rc = 1;
            } else {
                /* Convention: main() returns an int exit code or None. */
                if (PyLong_Check(result)) {
                    rc = (int)PyLong_AsLong(result);
                    if (rc == -1 && PyErr_Occurred()) { PyErr_Clear(); rc = 1; }
                }
                Py_DECREF(result);
            }
        }
        Py_DECREF(mod);
    }

    /* Free argv strings (skip the empty placeholders). */
    for (int i = 0; i < argc; i++) {
        if (wargv[i] && wargv[i][0]) PyMem_Free(wargv[i]);
    }
    PyMem_Free(wargv);

    if (Py_FinalizeEx() < 0) rc = 1;
    return rc;
}
'''


# ---------------------------------------------------------------------------
# MSVC environment discovery (find vcvars64.bat via vswhere)
# ---------------------------------------------------------------------------
def _find_vcvars64():
    """Return the path to vcvars64.bat, or None if MSVC is unavailable."""
    program_files_x86 = (os.environ.get('ProgramFiles(x86)')
                         or r'C:\Program Files (x86)')
    vswhere = os.path.join(program_files_x86, 'Microsoft Visual Studio',
                           'Installer', 'vswhere.exe')
    if not os.path.exists(vswhere):
        return None
    try:
        proc = subprocess.run(
            [vswhere, '-latest', '-products', '*',
             '-requires', 'Microsoft.VisualStudio.Component.VC.Tools.x86.x64',
             '-property', 'installationPath'],
            capture_output=True, text=True, timeout=20)
        vs_path = proc.stdout.strip()
        if not vs_path:
            return None
    except (OSError, subprocess.SubprocessError):
        return None
    vcvars = os.path.join(vs_path, 'VC', 'Auxiliary', 'Build', 'vcvars64.bat')
    return vcvars if os.path.exists(vcvars) else None


def _python_embed_paths():
    """Locate Python.h, python311.lib, python311.dll, stdlib for embedding.

    Returns a dict with keys: include_dir, lib_dir, python_lib (import
    library .lib), python_dlls (list of DLLs to ship), stdlib_dir.
    """
    base = sys.base_prefix
    include = sysconfig.get_path('include') or os.path.join(base, 'Include')
    lib_dir = os.path.join(base, 'libs')
    # python311.lib is the import library for linking against python311.dll.
    py_lib = os.path.join(lib_dir, 'python311.lib')
    if not os.path.exists(py_lib):
        # Fallback: try python3.lib (the stable-API stub).
        py_lib = os.path.join(lib_dir, 'python3.lib')
    dlls = []
    for name in ('python311.dll', 'python3.dll', 'vcruntime140.dll',
                 'vcruntime140_1.dll'):
        p = os.path.join(base, name)
        if os.path.exists(p):
            dlls.append(p)
    stdlib = sysconfig.get_path('stdlib') or os.path.join(base, 'Lib')
    return {
        'include_dir': include,
        'lib_dir': lib_dir,
        'python_lib': py_lib,
        'python_dlls': dlls,
        'stdlib_dir': stdlib,
        'base_prefix': base,
    }


# ---------------------------------------------------------------------------
# Build
# ---------------------------------------------------------------------------
def build_standalone_exe(obf_pyd_path, out_dir, *, exe_name='app.exe',
                          ship_stdlib=True, verbose=False):
    """Build a standalone ``app.exe`` that embeds CPython and imports ``obf``.

    Args:
      obf_pyd_path: path to the compiled ``obf.cp311-win_amd64.pyd``
      out_dir: output directory (where app.exe + DLLs + stdlib go)
      exe_name: output executable filename (default 'app.exe')
      ship_stdlib: also copy the stdlib tree into ``out_dir/Lib``
      verbose: print progress

    Returns a dict:
      - 'mode': 'standalone' | 'reference' (reference = no compiler)
      - 'exe_path': full path to app.exe, or None on failure
      - 'package_dir': out_dir (the dir to ship)
      - 'detail': status string
    """
    cap = detect_build_capability()
    if not cap['can_build']:
        return {'mode': 'reference', 'exe_path': None,
                'package_dir': out_dir,
                'detail': f"no native toolchain: {cap.get('detail','')}"}

    if not os.path.exists(obf_pyd_path):
        return {'mode': 'reference', 'exe_path': None,
                'package_dir': out_dir,
                'detail': f"obf .pyd not found: {obf_pyd_path}"}

    vcvars = _find_vcvars64()
    if not vcvars:
        return {'mode': 'reference', 'exe_path': None,
                'package_dir': out_dir,
                'detail': 'vcvars64.bat not found (MSVC BuildTools missing)'}

    paths = _python_embed_paths()
    if not os.path.exists(paths['python_lib']):
        return {'mode': 'reference', 'exe_path': None,
                'package_dir': out_dir,
                'detail': f"python311.lib not found at {paths['python_lib']}"}

    os.makedirs(out_dir, exist_ok=True)
    tmpdir = tempfile.mkdtemp(prefix='_bedrock_embed_')
    try:
        main_c = os.path.join(tmpdir, 'main.c')
        with open(main_c, 'w', encoding='utf-8') as f:
            f.write(_MAIN_C_TEMPLATE)

        exe_out = os.path.join(tmpdir, 'app.exe')
        # Compile + link in one cl invocation. vcvars64 sets INCLUDE/LIB for
        # the MSVC SDK; we add /I for Python.h and /LIBPATH for python311.lib.
        # /MD keeps the dynamic CRT consistent with the setuptools-built .pyd
        # (which defaults to /MD); we ship vcruntime140.dll alongside.
        # We write a temp .bat because cmd /c mangles inner quotes when the
        # vcvars path contains spaces; `call` inside a batch handles it.
        bat_path = os.path.join(tmpdir, '_build.bat')
        with open(bat_path, 'w', encoding='utf-8') as bf:
            bf.write('@echo off\n')
            bf.write(f'call "{vcvars}"\n')
            bf.write(
                f'cl /nologo /MD /O2 /GS- '
                f'/I"{paths["include_dir"]}" '
                f'"{main_c}" '
                f'/Fe:"{exe_out}" '
                f'/link /LIBPATH:"{paths["lib_dir"]}" '
                f'{os.path.basename(paths["python_lib"])} '
                f'/SUBSYSTEM:CONSOLE /INCREMENTAL:NO\n'
            )
        if verbose:
            print(f"[embed] building app.exe in {tmpdir}")
        proc = subprocess.run(
            ['cmd', '/c', bat_path], capture_output=True, text=True)
        if proc.returncode != 0 or not os.path.exists(exe_out):
            tail = (proc.stderr or proc.stdout or '')[-1500:]
            return {'mode': 'reference', 'exe_path': None,
                    'package_dir': out_dir,
                    'detail': f"cl link failed: {tail}"}

        # --- Ship the package: app.exe + .pyd + DLLs + stdlib + _pth ---
        dest_exe = os.path.join(out_dir, exe_name)
        shutil.copy2(exe_out, dest_exe)

        # The compiled obf extension.
        shutil.copy2(obf_pyd_path,
                      os.path.join(out_dir, os.path.basename(obf_pyd_path)))

        # CPython runtime DLLs (python311.dll, python3.dll, vcruntime140*.dll).
        for dll in paths['python_dlls']:
            shutil.copy2(dll, os.path.join(out_dir, os.path.basename(dll)))

        # stdlib tree. Ship the whole Lib/ for MVP correctness; a later pass
        # can prune to the subset the protected program actually imports.
        if ship_stdlib and os.path.isdir(paths['stdlib_dir']):
            dest_lib = os.path.join(out_dir, 'Lib')
            if os.path.abspath(dest_lib) != os.path.abspath(paths['stdlib_dir']):
                if os.path.isdir(dest_lib):
                    shutil.rmtree(dest_lib, ignore_errors=True)
                shutil.copytree(paths['stdlib_dir'], dest_lib,
                                dirs_exist_ok=True,
                                ignore=shutil.ignore_patterns(
                                    '__pycache__', '*.pyc', 'site-packages'))

        # python311._pth: tells CPython (embeddable-distribution convention)
        # to search Lib/ and the current dir, and to IGNORE PYTHONPATH / the
        # registry, so the package is fully self-contained.
        _pth = os.path.join(out_dir, 'python311._pth')
        with open(_pth, 'w', encoding='utf-8') as f:
            f.write('Lib\n.\n')

        if verbose:
            print(f"[embed] standalone mode -> {dest_exe}")
            print(f"[embed] package dir -> {out_dir}")
        return {
            'mode': 'standalone',
            'exe_path': dest_exe,
            'package_dir': out_dir,
            'detail': (f"shipped standalone {exe_name} + "
                       f"{os.path.basename(obf_pyd_path)} + python311.dll + "
                       f"stdlib"),
        }
    finally:
        shutil.rmtree(tmpdir, ignore_errors=True)


